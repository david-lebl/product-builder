package mpbuilder.catalog

import mpbuilder.shared.*

/** Typed domain errors for the Catalog & Configuration bounded context. */
enum CatalogError(val message: String):
  case CategoryNotFound(categoryId: CategoryId)
      extends CatalogError(s"Category '${categoryId.value}' not found")
  case MaterialNotFound(materialId: MaterialId)
      extends CatalogError(s"Material '${materialId.value}' not found")
  case FinishNotFound(finishId: FinishId)
      extends CatalogError(s"Finish '${finishId.value}' not found")
  case PrintingMethodNotFound(methodId: PrintingMethodId)
      extends CatalogError(s"Printing method '${methodId.value}' not found")
  case MissingRequiredComponent(categoryId: CategoryId, key: ComponentKey)
      extends CatalogError(s"Category '${categoryId.value}' requires component '${key.value}'")
  case UnexpectedComponent(categoryId: CategoryId, key: ComponentKey)
      extends CatalogError(s"Component '${key.value}' is not defined for category '${categoryId.value}'")
  case DuplicateComponent(key: ComponentKey)
      extends CatalogError(s"Duplicate component '${key.value}' in configuration")
  case MaterialNotAllowed(categoryId: CategoryId, key: ComponentKey, materialId: MaterialId)
      extends CatalogError(s"Material '${materialId.value}' is not allowed for '${categoryId.value}/${key.value}'")
  case FinishNotAllowed(categoryId: CategoryId, key: ComponentKey, finishId: FinishId)
      extends CatalogError(s"Finish '${finishId.value}' is not allowed for '${categoryId.value}/${key.value}'")
  case PrintingMethodNotAllowed(categoryId: CategoryId, key: ComponentKey, methodId: PrintingMethodId)
      extends CatalogError(s"Printing method '${methodId.value}' is not allowed for '${categoryId.value}/${key.value}'")
  case MissingPrintSpec(key: ComponentKey)
      extends CatalogError(s"Printable component '${key.value}' requires printing method and ink configuration")
  case UnexpectedPrintSpec(key: ComponentKey)
      extends CatalogError(s"Non-printable component '${key.value}' must not carry printing method or ink")
  case InkExceedsMethodColorLimit(methodId: PrintingMethodId, key: ComponentKey, actual: Int, maxAllowed: Int)
      extends CatalogError(s"Ink colors ($actual) on '${key.value}' exceed method '${methodId.value}' limit ($maxAllowed)")
  case DoubleSidedNotSupported(methodId: PrintingMethodId, key: ComponentKey)
      extends CatalogError(s"Printing method '${methodId.value}' does not support double-sided printing on '${key.value}'")
  case UnsupportedSpecialInk(methodId: PrintingMethodId, key: ComponentKey, ink: SpecialInk)
      extends CatalogError(s"Printing method '${methodId.value}' does not support special ink $ink on '${key.value}'")
  case InvalidFinishSide(finishId: FinishId, detail: String)
      extends CatalogError(s"Invalid finish side for '${finishId.value}': $detail")
  case InvalidFinishParameters(finishId: FinishId, detail: String)
      extends CatalogError(s"Invalid finish parameters for '${finishId.value}': $detail")
  case MissingRequiredSpecification(categoryId: CategoryId, specName: String)
      extends CatalogError(s"Category '${categoryId.value}' requires specification: $specName")
  case FlatSizeExceedsAllStockFormats(key: ComponentKey, materialId: MaterialId, flatSize: Dimension2D)
      extends CatalogError(
        s"Flat size ${flatSize.width.value}×${flatSize.height.value}mm on '${key.value}' exceeds all stock formats of '${materialId.value}'"
      )
  case RuleViolation(ruleId: RuleId, reason: LocalizedString)
      extends CatalogError(s"Rule '${ruleId.value}' violated: ${reason(Language.En)}")
  case RuleNotFound(ruleId: RuleId)
      extends CatalogError(s"Rule '${ruleId.value}' not found")
  case EntityInUse(entityType: String, entityId: String, usedBy: List[String])
      extends CatalogError(s"Cannot delete $entityType '$entityId': still referenced by ${usedBy.mkString(", ")}")
  case ConfigurationValidationFailed(errors: NonEmptyChunk[CatalogError])
      extends CatalogError(s"Configuration failed with ${errors.size} error(s): ${errors.map(_.message).mkString("; ")}")
